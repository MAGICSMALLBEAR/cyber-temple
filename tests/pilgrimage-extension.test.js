const { makeEnvironment } = require("./light-env");
module.exports = {
  name: "八步參拜、主題備供與角色道具（無繪圖）",
  async run({ check, note }) {
    const THREE = await import("three"), env = makeEnvironment(THREE), c = env.context;
    for (const file of ["scene/service.js", "inventory.js"]) {
      if (file === "scene/service.js") c.installTempleMixin = () => {};
      env.load(file);
    }
    env.load("app/pilgrimage.js");
    const bag = c.templeInventory, flow = c.pilgrimage;
    c.temple3d = { avatar: { position: new THREE.Vector3(-4.1, 0, 8.2), playerGroup: new THREE.Group(), triggerAction() {} } };
    c.addMerit = n => { c.state.meritCount += n; };
    flow.init();
    const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);
    check("八步包含收供，且舊步驟名稱保持可辨識", env.run("PILGRIM_STEPS.length") === 8 && env.run("PILGRIM_STEPS[6].id") === "collect");
    check("五種主題皆有五份合法供品", Object.keys(bag.offeringSets).length === 5 && Object.values(bag.offeringSets).every(set => set.dishes.length === 5 && set.dishes.every(id => bag.isOffering(id))));
    const beforeSlots = bag.data.offering.slots;
    check("選主題只預覽，不改桌面或扣款", bag.selectOfferingSet("wealth") && same(bag.data.offering.slots, beforeSlots) && bag.data.coins === 60 && !bag.selectOfferingSet("fake"));
    check("祝壽雙份仙桃正確計數", bag.offeringSetNeeds("birthday").peach === 2);
    let d = bag.load(); d.coins = 100; bag.save(d);
    const needs = bag.offeringSetNeeds(), quote = bag.restockQuote(needs);
    check("招財組缺額價格正確", quote.total === 54);
    check("補買主題組合只買缺額並提起供品籃", bag.buyRestock(needs, quote.total).ok && bag.data.coins === 46 && bag.data.carryMode === "basket" && bag.restockQuote(needs).total === 0);
    check("主題購買完成不會自動擺上桌", bag.data.offering.slots.every(id => !id));
    c.temple3d.avatar.position.set(0, 0, 1.7);
    check("主題組合可一鍵擺上、保持庫存守恆", bag.placeOfferingSet(bag.offeringSets.wealth.dishes).ok && same(bag.data.offering.slots, bag.offeringSets.wealth.dishes) && bag.data.items.goldIngot === 0);
    bag.collectOfferings();
    c.temple3d.avatar.position.set(-4.1, 0, 8.2);
    flow.start();
    check("沒有香紙時不能確認材料或偽造備齊事件", !flow.confirmSupplies() && flow.step.id === "supplies");
    c.emitRitual("supplies"); check("材料不足的科儀事件不推進", flow.step.id === "supplies");
    d = bag.load(); d.items.incense = 2; d.items.paper = 1; bag.save(d);
    check("材料齊備且在現場才前進", flow.confirmSupplies() && flow.step.id === "heaven");
    c.temple3d.avatar.position.set(0, 0, 1.7); c.emitRitual("heavenCenser");
    check("遠端完成敬天不算數", flow.step.id === "heaven");
    c.temple3d.avatar.position.set(0, 0, 9.6); bag.consume({ incense: 1 }); c.emitRitual("heavenCenser");
    check("敬天完成後接續正殿上香", flow.step.id === "main");
    c.temple3d.avatar.position.set(0, 0, 1.7); bag.consume({ incense: 1 }); c.emitRitual("incense");
    bag.placeOfferingSet(bag.offeringSets.wealth.dishes); bag.presentOfferings(); c.emitRitual("feast");
    c.emitRitual("bow"); check("一般鞠躬不能代替跪拜", flow.step.id === "kneel");
    c.emitRitual("bow", { action: "kneel" }); c.emitRitual("chiamReceived");
    check("求籤仍需要聖筊確認", flow.step.id === "chiam");
    c.emitRitual("chiamReceived", { confirmed: true });
    check("求籤後接到收供，不直接跳化紙", flow.step.id === "collect");
    c.emitRitual("offeringsCollected", { all: true });
    check("桌上仍有物品時不能偽造收供完成", flow.step.id === "collect");
    bag.collectOfferings(); check("實際全部收供才進到化紙", flow.step.id === "paper" && bag.data.items.goldIngot === 1);
    c.temple3d.avatar.position.set(-12.5, 0, 12.3); bag.consume({ paper: 1 }); c.emitRitual("paper");
    check("八步完成只發一次圓滿獎勵", !flow.data.active && flow.data.completed === 1 && c.state.meritCount === 168);
    c.emitRitual("paper"); check("重送最後事件不重複獎勵", c.state.meritCount === 168);
    // 已提早收好的供品不要求再擺一桌才能完成收供步驟。
    flow.start(); flow.data.step = 6; c.temple3d.avatar.position.set(0, 0, 1.7); flow.primary();
    check("提早收供或空桌可現場確認繼續", flow.step.id === "paper");
    const legacy = step => { c.localStorage.setItem("temple_pilgrimage", JSON.stringify({ active: true, step, completed: 9 })); return flow.load(); };
    check("舊第六步求籤保持原進度與次數", legacy(5).step === 5 && flow.load().completed === 9);
    check("舊化紙進度在空桌時接到新第八步", legacy(6).step === 7);
    bag.placeOffering(0, "goldIngot");
    check("舊化紙進度有供品時先接收供", legacy(6).step === 6);
    flow.data = { active: true, step: 7, completed: 9 }; flow.save();
    check("新版依步驟 ID 保存與讀回", flow.load().step === 7 && JSON.parse(c.localStorage.getItem("temple_pilgrimage")).stepId === "paper");
    c.localStorage.setItem("temple_pilgrimage", JSON.stringify({ active: true, step: 999, completed: 9 }));
    check("壞進度安全停止但保留已完成次數", !flow.load().active && flow.load().completed === 9);

    for (const file of ["avatar/appearance.js", "avatar/core.js", "avatar/ritual-props.js", "avatar/social.js", "avatar/relics.js", "avatar/companions.js"]) env.load(file);
    const a = Object.create(c.TempleAvatarSystem.prototype), messages = [];
    a.scene = new THREE.Scene(); a.playerGroup = new THREE.Group(); a.scene.add(a.playerGroup); a.position = new THREE.Vector3(); a.limbs = {};
    a.config = { ...env.run("AVATAR_DEFAULT_LOOK"), robeColor: "#93422b", holdingItem: "incense", title: "測試善信", hatType: "none" };
    a.currentAction = "idle"; a.actionProgress = 0; a.keys = {}; a.relics = {}; a.peers = new Map(); a.lastBroadcastPos = new THREE.Vector3(); a.lastBroadcastTime = 0;
    a.channel = { postMessage: data => messages.push(data) }; a.myPeerId = "self"; a.buildAvatarMesh();
    a.setRitualCarry("basket"); a.animateLimbs(1, .016);
    check("提籃有實際模型並暫時隱藏原持物", !!a.ritualProps.basket?.visible && !a.limbs.heldObject.visible && a.config.holdingItem === "incense");
    a.currentAction = "walk"; a.animateLimbs(1.1, .016);
    check("提籃行走仍有腿部步伐", a.ritualProps.basket.visible && Math.abs(a.limbs.legL.rotation.x) > .01);
    a.setRitualCarry("tray"); a.currentAction = "idle"; a.animateLimbs(1.2, .016);
    check("端盤使用雙手且只有一個參拜道具顯示", a.ritualProps.tray.visible && !a.ritualProps.basket.visible && a.limbs.armL.rotation.x < -1 && a.limbs.armR.rotation.x < -1);
    a.setRitualCarry(""); a.animateLimbs(1.3, .016);
    check("放下道具恢復原持物與設定", !a.ritualProps.tray.visible && a.limbs.heldObject.visible && a.config.holdingItem === "incense");
    const baseTime = c.Date.now();
    a.playRitualMotion("placeOffering"); env.setTime(new Date(baseTime + 650).toISOString()); a.animateLimbs(1.5, .016);
    check("擺供有前伸端盤動作", a.ritualProps.tray.visible && a.ritualProps.tray.position.z > .5 && a.limbs.torso.rotation.x > .1);
    a.playRitualMotion("incenseOffering"); env.setTime(new Date(baseTime + 1000).toISOString()); a.animateLimbs(1.6, .016);
    check("持香行禮有三炷清香及俯首姿勢", a.ritualProps.incense.visible && a.ritualProps.incense.children.length === 6 && a.limbs.head.rotation.x > 0);
    const payload = messages.at(-1); payload.id = "other";
    a.handlePeerUpdate(payload); const peer = a.peers.get("other"); a.animatePeerLimbs(peer, 1.6, .016);
    check("同行收到同款參拜道具與動作", peer.ritualProps.incense.visible && peer.ritualMotion.name === "incenseOffering");
    env.setTime(new Date(baseTime + 5000).toISOString()); a.animateLimbs(5, .016); a.animatePeerLimbs(peer, 5, .016);
    check("自己與同行的短動作會到期並恢復持物", !a.ritualMotion && !peer.ritualMotion && !a.ritualProps.incense.visible && a.limbs.heldObject.visible);
    a.playRitualMotion("presentOffering"); a.currentAction = "walk"; a.animateLimbs(5.1, .016);
    check("移動可中斷獻供動作，不會鎖住角色", !a.ritualMotion);
    a.setRitualCarry("tray"); a.triggerAction("kneelSit"); a.animateLimbs(5.2, .016);
    check("跪坐時暫時放下供盤", !a.ritualProps.tray.visible);
    const invalid = env.run('normalizeRitualState({carry:"fake", motion:{name:"incenseOffering",startedAt:Infinity}})');
    check("拒絕不合法的同行道具與時序", invalid.carry === "" && invalid.motion === null);
    let peerReleased = 0; Object.values(peer.ritualProps).forEach(prop => prop.traverse(o => o.geometry?.addEventListener("dispose", () => peerReleased++)));
    a.handlePeerUpdate({ ...payload, config: { ...payload.config, robeColor: "#224488" } });
    check("同行換裝會釋放舊參拜道具", peerReleased > 0);
    c.templeMotion = { reduced: true }; a.playRitualMotion("incenseOffering"); a.animateLimbs(5.3, .016);
    const reducedPose = a.limbs.torso.rotation.x; env.setTime(new Date(c.Date.now() + 500).toISOString()); a.animateLimbs(5.8, .016);
    check("減少動態時持香姿勢維持穩定", reducedPose === .08 && a.limbs.torso.rotation.x === reducedPose);
    let released = 0; Object.values(a.ritualProps).forEach(prop => prop.traverse(o => o.geometry?.addEventListener("dispose", () => released++)));
    a.buildAvatarMesh(); check("換裝釋放舊參拜道具幾何", released > 10 && Object.keys(a.ritualProps).length === 0);
    note("實際存檔、八步科儀事件與 Three.js 角色／同行幾何；不建立 WebGLRenderer。");
  }
};
